import { spawnSync } from "node:child_process";
import { createClient } from "@supabase/supabase-js";
import { afterAll, beforeAll, expect, it } from "vitest";
import { fetchRequest, type Env } from "../../worker/index";
const ids = Array.from({ length: 5 }, () => crypto.randomUUID());
const [tenantA, tenantB] = ids;
let env: Env, admin: ReturnType<typeof createClient>;
const users: string[] = [];
const password = `Local-only-${crypto.randomUUID()}!`;
function sql(input: string) {
  const r = spawnSync(
    "docker",
    [
      "exec",
      "-i",
      "supabase_db_menuflow-local",
      "psql",
      "-X",
      "-U",
      "postgres",
      "-v",
      "ON_ERROR_STOP=1",
    ],
    { input, encoding: "utf8" },
  );
  if (r.status !== 0) throw new Error(r.stderr);
}
async function api(path: string, cookie = "", data?: unknown, method = "POST") {
  const r = await fetchRequest(
    new Request(`https://app.test/api/v1${path}`, {
      method: data === undefined ? "GET" : method,
      headers: {
        origin: "https://app.test",
        cookie,
        "content-type": "application/json",
      },
      body: data === undefined ? undefined : JSON.stringify(data),
    }),
    env,
  );
  return r;
}
beforeAll(async () => {
  const result = spawnSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["--yes", "supabase", "status", "-o", "json"],
    { encoding: "utf8", shell: process.platform === "win32" },
  );
  if (result.status !== 0)
    throw new Error("Start the isolated MenuFlow local Supabase stack first.");
  const status = JSON.parse(result.stdout);
  if (!status.API_URL?.startsWith("http://127.0.0.1:55431"))
    throw new Error(
      "Integration tests require the dedicated local Supabase instance.",
    );
  env = {
    SUPABASE_URL: status.API_URL,
    SUPABASE_PUBLISHABLE_KEY: status.ANON_KEY,
    SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  };
  admin = createClient(status.API_URL, status.SERVICE_ROLE_KEY, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  for (let i = 0; i < 3; i++) {
    const { data, error } = await admin.auth.admin.createUser({
      email: `menuflow-${ids[i]}@example.test`,
      password,
      email_confirm: true,
    });
    if (error || !data.user)
      throw new Error("Local test user provisioning failed");
    users.push(data.user.id);
  }
  sql(`insert into tenants(id,name,slug) values('${tenantA}','Integration A','a-${tenantA}'),('${tenantB}','Integration B','b-${tenantB}');
 insert into tenant_settings(tenant_id) values('${tenantA}'),('${tenantB}');
 insert into memberships(tenant_id,user_id,role) values('${tenantA}','${users[0]}','owner'),('${tenantB}','${users[1]}','owner'),('${tenantA}','${users[2]}','staff');`);
});
afterAll(async () => {
  if (!admin) return;
  // The UUIDs above are generated by this test; cleanup cannot touch other tenants.
  sql(
    `delete from audit_logs where tenant_id in('${tenantA}','${tenantB}');delete from table_qr_tokens where tenant_id in('${tenantA}','${tenantB}');delete from products where tenant_id in('${tenantA}','${tenantB}');delete from categories where tenant_id in('${tenantA}','${tenantB}');delete from dining_tables where tenant_id in('${tenantA}','${tenantB}');delete from memberships where tenant_id in('${tenantA}','${tenantB}');delete from audit_logs where tenant_id in('${tenantA}','${tenantB}');delete from tenant_settings where tenant_id in('${tenantA}','${tenantB}');delete from tenants where id in('${tenantA}','${tenantB}');`,
  );
  for (const id of users) await admin.auth.admin.deleteUser(id);
});
it("real Auth → owner menu/image/table → QR → tenant isolation → revocation", async () => {
  async function login(index: number) {
    const r = await api("/auth/login", "", {
      email: `menuflow-${ids[index]}@example.test`,
      password,
    });
    expect(r.status).toBe(200);
    expect(await r.json()).toEqual({ authenticated: true });
    return r.headers.get("set-cookie")!.split(";")[0];
  }
  const owner = await login(0),
    other = await login(1),
    staff = await login(2);
  expect((await api("/admin/memberships", owner)).status).toBe(200);
  let r = await api(`/admin/categories?tenant=${tenantA}`, owner, {
    name: "Coffee",
  });
  expect(r.status).toBe(201);
  const category = (await r.json()).id;
  r = await api(`/admin/products?tenant=${tenantA}`, owner, {
    name: "Espresso",
    category_id: category,
    price_minor: 12345,
  });
  expect(r.status).toBe(201);
  const product = (await r.json()).id;
  r = await api(`/admin/tables?tenant=${tenantA}`, owner, { name: "Table 9" });
  expect(r.status).toBe(201);
  const table = (await r.json()).id;
  r = await api(`/admin/tables/${table}/qr?tenant=${tenantA}`, owner, {});
  expect(r.status).toBe(200);
  const token = (await r.json()).url.split("#")[1];
  expect((await api("/menu", "", { token })).status).toBe(404);
  expect(
    (await api(`/admin/publish?tenant=${tenantA}`, owner, { published: true }))
      .status,
  ).toBe(200);
  const bytes = Buffer.from(
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jhS8AAAAASUVORK5CYII=",
    "base64",
  );
  r = await fetchRequest(
    new Request(
      `https://app.test/api/v1/admin/products/${product}/image?tenant=${tenantA}`,
      {
        method: "POST",
        headers: {
          origin: "https://app.test",
          cookie: owner,
          "content-type": "image/png",
        },
        body: bytes,
      },
    ),
    env,
  );
  expect(r.status).toBe(200);
  const image = (await r.json()).image_path;
  r = await api("/menu", "", { token, tenant_id: tenantB });
  expect(r.status).toBe(200);
  const menu = await r.json();
  expect(menu.tenant.name).toBe("Integration A");
  expect(menu.table.name).toBe("Table 9");
  expect(menu.products[0].price_minor).toBe(12345);
  expect(menu.products[0].image_path).toBeUndefined();
  expect(menu.products[0].image_url).toBeTruthy();
  expect((await fetch(menu.products[0].image_url)).status).toBe(200);
  const b = createClient(env.SUPABASE_URL!, env.SUPABASE_PUBLISHABLE_KEY!, {
    global: {
      headers: { authorization: `Bearer ${other.slice("mf_admin=".length)}` },
    },
    auth: { persistSession: false, autoRefreshToken: false },
  });
  expect(
    (await b.storage.from("menu-images").download(image)).error,
  ).toBeTruthy();
  expect(
    (
      await api(
        `/admin/products/${product}?tenant=${tenantA}`,
        owner,
        { remove_image: true },
        "PATCH",
      )
    ).status,
  ).toBe(200);
  expect(
    (await admin.storage.from("menu-images").download(image)).error,
  ).toBeTruthy();
  expect((await api(`/admin/products?tenant=${tenantA}`, other)).status).toBe(
    403,
  );
  expect(
    (
      await api(
        `/admin/products/${product}?tenant=${tenantA}`,
        staff,
        { price_minor: 1 },
        "PATCH",
      )
    ).status,
  ).toBe(403);
  expect(
    (await api(`/admin/tables/${table}/qr?tenant=${tenantA}`, owner, {}))
      .status,
  ).toBe(200);
  expect((await api("/menu", "", { token })).status).toBe(404);
  const membership = (
    await (await api(`/admin/staff?tenant=${tenantA}`, owner)).json()
  ).find((row: { user_id: string }) => row.user_id === users[2]);
  expect(
    (
      await api(
        `/admin/staff/${membership.id}?tenant=${tenantA}`,
        owner,
        { active: false },
        "PATCH",
      )
    ).status,
  ).toBe(200);
  expect((await api(`/admin/products?tenant=${tenantA}`, staff)).status).toBe(
    403,
  );
  expect(
    (await api("/auth/logout", owner, {})).headers.get("set-cookie"),
  ).toContain("Max-Age=0");
  await admin.storage.from("menu-images").remove([image]);
});
